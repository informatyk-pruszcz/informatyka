async function copyText(text, toast) {
  try {
    await navigator.clipboard.writeText(text);
    toast('✓ Skopiowano do schowka! Możesz teraz wkleić (Ctrl + V) w edytorze tekstu.');
  } catch {
    const ta = document.createElement('textarea');
    ta.value = text;
    ta.style.position = 'fixed';
    ta.style.opacity = '0';
    document.body.appendChild(ta);
    ta.select();
    document.execCommand('copy');
    ta.remove();
    toast('✓ Skopiowano do schowka!');
  }
}

export function bindWorksheet(id, toast) {
  const sheet = document.getElementById('ws-sheet');
  if (!sheet) return;

  const STORAGE_KEY = 'informatyka-ws-progress-v1';
  let state = {};
  try {
    state = JSON.parse(localStorage.getItem(STORAGE_KEY) || '{}');
  } catch {
    state = {};
  }

  // Restore student name & class across worksheets
  const nameInput = document.getElementById('ws-student-name');
  const classInput = document.getElementById('ws-student-class');
  const filenamePreview = document.getElementById('ws-filename-preview');

  function sanitizeFilePart(str, fallback) {
    const cleaned = (str || '')
      .trim()
      .normalize('NFD')
      .replace(/[\u0300-\u036f]/g, '')
      .replace(/ł/g, 'l')
      .replace(/Ł/g, 'L')
      .replace(/[^a-zA-Z0-9]+/g, '_')
      .replace(/^_+|_+$/g, '');
    return cleaned || fallback;
  }

  function updateFilenames() {
    if (!filenamePreview) return;
    const prefix = filenamePreview.dataset.prefix || 'Plik';
    const ext = filenamePreview.dataset.ext || '';
    const rawName = nameInput?.value.trim() || '';
    const parts = rawName ? rawName.split(/\s+/) : [];
    const imie = sanitizeFilePart(parts[0], 'Imie');
    const nazwisko = sanitizeFilePart(parts.slice(1).join('_'), 'Nazwisko');
    const full = `${prefix}_${imie}_${nazwisko}${ext}`;
    filenamePreview.textContent = full;
    document.querySelectorAll(`[data-filename-slot="${prefix}"]`).forEach(el => {
      el.textContent = full;
    });
  }

  if (nameInput) {
    nameInput.value = state.studentName || '';
    nameInput.addEventListener('input', () => {
      state.studentName = nameInput.value;
      try { localStorage.setItem(STORAGE_KEY, JSON.stringify(state)); } catch {}
      updateFilenames();
    });
  }
  if (classInput && state.studentClass) {
    classInput.value = state.studentClass;
  }
  if (classInput) {
    classInput.addEventListener('input', () => {
      state.studentClass = classInput.value;
      try { localStorage.setItem(STORAGE_KEY, JSON.stringify(state)); } catch {}
    });
  }
  updateFilenames();

  const copyFilenameBtn = document.getElementById('ws-copy-filename');
  if (copyFilenameBtn && filenamePreview) {
    copyFilenameBtn.onclick = () => copyText(filenamePreview.textContent, toast);
  }

  // Copy buttons for raw text and step 4 sentences
  document.querySelectorAll('[data-copy-target]').forEach(btn => {
    btn.onclick = () => {
      const target = btn.dataset.copyTarget;
      if (target === 'zupa-raw') copyText(ZUPA_RAW_TEXT, toast);
      else if (target === 'zupa-step4') copyText(ZUPA_STEP4_TEXT, toast);
      else if (target === 'tosty-raw') copyText(TOSTY_RAW_TEXT, toast);
      else if (target === 'tosty-step4') copyText(TOSTY_STEP4_TEXT, toast);
    };
  });

  // Copy table cells / chips in Planer
  document.querySelectorAll('[data-copy-cell]').forEach(el => {
    el.onclick = () => copyText(el.dataset.copyCell, toast);
  });

  // Checkboxes & progress bar
  const checks = [...sheet.querySelectorAll('[data-step-check]')];
  const progressLabel = document.getElementById('ws-progress-label');
  const progressFill = document.getElementById('ws-progress-fill');

  function updateProgress(triggerToast = false) {
    if (!checks.length) return;
    const done = checks.filter(c => c.checked).length;
    const pct = Math.round((done / checks.length) * 100);
    if (progressLabel) {
      progressLabel.innerHTML = `Twój postęp na karcie pracy: <strong>${done} / ${checks.length} (${pct}%)</strong>`;
    }
    if (progressFill) {
      progressFill.style.width = `${pct}%`;
    }
    checks.forEach(c => {
      const stepCard = c.closest('.ws-step');
      if (stepCard) stepCard.classList.toggle('ws-step-done', c.checked);
    });
    if (triggerToast && done === checks.length) {
      toast('🎉 Brawo! Wszystkie kroki i punkty autotestu na tej karcie pracy zostały ukończone!');
    }
  }

  checks.forEach(c => {
    const key = c.dataset.stepCheck;
    c.checked = !!state[key];
    c.addEventListener('change', () => {
      state[key] = c.checked;
      try { localStorage.setItem(STORAGE_KEY, JSON.stringify(state)); } catch {}
      updateProgress(true);
    });
  });
  updateProgress(false);

  const resetBtn = document.getElementById('ws-reset-progress');
  if (resetBtn) {
    resetBtn.onclick = () => {
      checks.forEach(c => {
        c.checked = false;
        delete state[c.dataset.stepCheck];
      });
      try { localStorage.setItem(STORAGE_KEY, JSON.stringify(state)); } catch {}
      updateProgress(false);
      toast('Wyczyszczono odhaczone punkty na tej karcie.');
    };
  }

  // Interactive simulator
  const simPage = document.getElementById('ws-sim-page');
  const simRibbon = document.getElementById('ws-sim-ribbon');
  const simTabs = [...document.querySelectorAll('.ws-sim-tab')];

  function setSimStep(step) {
    if (!simPage || !simRibbon) return;
    const kind = simPage.dataset.simKind;
    const { ribbon, page } = getSimContent(kind, step);
    simRibbon.innerHTML = ribbon;
    simPage.innerHTML = page;
    simTabs.forEach(t => t.classList.toggle('active', t.dataset.simStep === String(step)));
  }

  simTabs.forEach(t => {
    t.onclick = () => setSimStep(t.dataset.simStep);
  });
  setSimStep(1);

  // Step focus pills
  const focusPills = [...document.querySelectorAll('[data-focus-step]')];
  const stepCards = [...sheet.querySelectorAll('.ws-step')];

  function setFocusStep(step) {
    focusPills.forEach(p => p.classList.toggle('active', p.dataset.focusStep === String(step)));
    stepCards.forEach(card => {
      const match = step === 'all' || card.dataset.step === String(step);
      card.classList.toggle('ws-step-dimmed', !match);
      card.classList.toggle('ws-step-active', step !== 'all' && match);
    });
    if (step !== 'all') {
      setSimStep(step);
      const targetCard = stepCards.find(c => c.dataset.step === String(step));
      targetCard?.scrollIntoView({ behavior: 'smooth', block: 'nearest' });
    }
  }

  focusPills.forEach(pill => {
    pill.onclick = () => setFocusStep(pill.dataset.focusStep);
  });

  // Large text toggle & Print
  const largeBtn = document.getElementById('ws-toggle-large');
  if (largeBtn) {
    largeBtn.onclick = () => {
      const active = sheet.classList.toggle('ws-large-text');
      largeBtn.setAttribute('aria-pressed', String(active));
      largeBtn.textContent = active ? '🔍 Zwykły rozmiar tekstu' : '🔍 Powiększ tekst';
    };
  }

  const printBtn = document.getElementById('ws-print');
  if (printBtn) {
    printBtn.onclick = () => window.print();
  }
}
